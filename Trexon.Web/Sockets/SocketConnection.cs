using System.Net.WebSockets;
using System.Security.Claims;
using System.Text;
using System.Text.Json;
using Microsoft.AspNetCore.Http;

namespace Trexon.Web.Sockets;

/// <summary>A typed connection. Framing, JSON, send serialization and room membership are managed by the library.</summary>
public sealed class SocketConnection<T>
{
    private readonly SocketPeer _peer;
    private readonly SocketRoom _room;
    private readonly JsonSerializerOptions _json;
    internal SocketConnection(SocketPeer peer, SocketRoom room, JsonSerializerOptions json)
    { _peer = peer; _room = room; _json = json; }

    /// <summary>The unique connection ID, generated by the server.</summary>
    public string Id => _peer.Id;
    /// <summary>The identity established during the HTTP handshake.</summary>
    public ClaimsPrincipal User => _peer.Context.User;
    /// <summary>The HTTP request context, available for advanced integrations.</summary>
    public HttpContext HttpContext => _peer.Context;
    /// <summary>The connection's request/shutdown cancellation token.</summary>
    public CancellationToken CancellationToken => _peer.Token;
    /// <summary>Gets a route parameter without binding a controller model.</summary>
    public string? Route(string name) => _peer.Context.Request.RouteValues[name]?.ToString();
    /// <summary>Joins a named group within this endpoint. This is an in-memory operation.</summary>
    public void Join(string group) => _peer.Join(group);
    /// <summary>Leaves a group. Membership is also removed automatically on disconnect.</summary>
    public void Leave(string group) => _peer.Leave(group);
    /// <summary>Sends one typed message; string payloads are plain UTF-8 text, other types are JSON.</summary>
    public ValueTask SendAsync(T message, CancellationToken cancellationToken = default) =>
        _peer.SendAsync(Encode(message), cancellationToken);
    /// <summary>Sends to connected peers on this endpoint, including the sender; optionally restricts to a group.</summary>
    public ValueTask BroadcastAsync(T message, string? group = null, CancellationToken cancellationToken = default) =>
        _room.BroadcastAsync(Encode(message), group, _peer.Token, cancellationToken);
    /// <summary>Requests a normal close; the library completes the bounded closing handshake.</summary>
    public ValueTask CloseAsync(string reason = "Connection closed", CancellationToken cancellationToken = default) =>
        _peer.RequestCloseAsync(WebSocketCloseStatus.NormalClosure, reason, cancellationToken);
    private byte[] Encode(T message)
    {
        var payload = typeof(T) == typeof(string)
            ? Encoding.UTF8.GetBytes((string?)(object?)message ?? throw new ArgumentNullException(nameof(message)))
            : JsonSerializer.SerializeToUtf8Bytes(message, _json);
        _peer.CheckPayloadSize(payload.Length);
        return payload;
    }
}
